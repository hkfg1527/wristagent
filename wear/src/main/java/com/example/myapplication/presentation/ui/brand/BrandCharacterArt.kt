/** 某品牌此刻该展示的角色；没有专属角色时退回 [BrandId.UNKNOWN]。 */
internal fun characterFor(brand: BrandId): BrandCharacterArt =
    BrandCharacters[brand] ?: BrandCharacters.getValue(BrandId.UNKNOWN)

/**
 * 画一个角色。[eyeColor] 必须是它背后的实际底色，眼睛才是"洞"而不是脏点。
 */
@Composable
internal fun BrandCharacter(
    brand: BrandId,
    eyeColor: Color,
    modifier: Modifier = Modifier
) {
    val art = remember(brand) { characterFor(brand) }
    val ink = brand.accent
    Canvas(modifier = modifier) {
        val step = size.minDimension / CharacterGrid
        if (step <= 0f) return@Canvas
        drawGrid(art.body, step, ink)
        drawGrid(art.eyes, step, eyeColor)
    }
}

private fun DrawScope.drawGrid(bitmap: String, step: Float, color: Color) {
    val rows = bitmap.split('/')
    val radius = step / 2f
    for (row in 0 until CharacterGrid) {
        val line = rows.getOrNull(row) ?: continue
        for (col in 0 until CharacterGrid) {
            if (line.getOrNull(col) != '#') continue
            drawCircle(
                color = color,
                radius = radius,
                center = androidx.compose.ui.geometry.Offset(
                    x = (col + 0.5f) * step,
                    y = (row + 0.5f) * step
                )
            )
        }
    }
}

/** 角色建议尺寸：卡片里 48dp，独立展示 72dp。 */
internal object BrandCharacterSize {
    val Inline = 48.dp
    val Hero = 72.dp
}
