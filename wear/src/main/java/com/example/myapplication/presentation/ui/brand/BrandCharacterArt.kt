 * 品牌拟人角色：**点阵画**，与品牌标识（[BrandId.markRes] 那套矢量）是两套完全独立的资产。
 *
 * 为什么用点阵而不是矢量插画：整个应用的背景就是规则点阵，主键按下会顶开点阵。
 * 让角色也长在同一张点阵屏上，11 家厂商才像一家人，48dp 上也不会糊成一团像素噪声。
 *
 * 编码：[body] / [eyes] 是同一张 12×12 的格点图，'#' 画点、'.' 留空，行与行之间用 '/' 分隔。
